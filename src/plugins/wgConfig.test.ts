import { describe, expect, it } from 'vitest'
import { parseWireguardConf } from './wgConfig'

const standard = `[Interface]
PrivateKey = YNXtAzepDqRv9H52osJVDQnznT5AM11eCK3ESpwSt04=
Address = 10.0.0.2/32, fd00::2/128
DNS = 1.1.1.1, 8.8.8.8
MTU = 1408
ListenPort = 0

[Peer]
PublicKey = Z1XXLsKYkYxuiYjJIkRvtIKFepCYHTgON+GwPq7SOV4=
Endpoint = vpn.example.com:51820
AllowedIPs = 0.0.0.0/0, ::/0
PersistentKeepalive = 25
PresharedKey = 31aIhAPwktDGpH4JDhA8GNvjFXEf/a6+UaQRyOAiyfM=
`

describe('parseWireguardConf', () => {
  it('maps the interface block and peer into an endpoint', () => {
    const endpoint = parseWireguardConf(standard)

    expect(endpoint.type).toBe('wireguard')
    expect(endpoint.tag).toMatch(/^wireguard-/)
    expect(endpoint.private_key).toBe('YNXtAzepDqRv9H52osJVDQnznT5AM11eCK3ESpwSt04=')
    expect(endpoint.address).toEqual(['10.0.0.2/32', 'fd00::2/128'])
    expect(endpoint.listen_port).toBe(0)
    expect(endpoint.mtu).toBe(1408)
    expect(endpoint.ext.server).toBe('vpn.example.com')
    expect(endpoint.ext.dns).toBe('1.1.1.1,8.8.8.8')

    expect(endpoint.peers).toHaveLength(1)
    expect(endpoint.peers[0]).toMatchObject({
      address: 'vpn.example.com',
      port: 51820,
      public_key: 'Z1XXLsKYkYxuiYjJIkRvtIKFepCYHTgON+GwPq7SOV4=',
      allowed_ips: ['0.0.0.0/0', '::/0'],
      persistent_keepalive_interval: 25,
      pre_shared_key: '31aIhAPwktDGpH4JDhA8GNvjFXEf/a6+UaQRyOAiyfM=',
    })
  })

  it('reads comments, mixed case keys, CRLF and repeated lines', () => {
    const conf = `# generated by wg-quick\r\n[Interface]\r\nprivatekey = key\r\naddress = 10.9.0.2/32\r\naddress = fd00::9/128\r\n; ignored\r\n[Peer]\r\npublickey = peer\r\nallowedips = 10.9.0.0/24\r\nendpoint = 192.0.2.1:1234\r\n`
    const endpoint = parseWireguardConf(conf)

    expect(endpoint.address).toEqual(['10.9.0.2/32', 'fd00::9/128'])
    expect(endpoint.peers[0].address).toBe('192.0.2.1')
    expect(endpoint.peers[0].port).toBe(1234)
  })

  it('parses a bracketed IPv6 peer endpoint and defaults a missing port', () => {
    const conf = `[Interface]\nPrivateKey = key\nAddress = 10.0.0.2/32\n[Peer]\nPublicKey = peer\nAllowedIPs = 0.0.0.0/0\nEndpoint = [2001:db8::1]:51820\n[Peer]\nPublicKey = peer2\nAllowedIPs = ::/0\nEndpoint = vpn.example.net\n`
    const endpoint = parseWireguardConf(conf)

    expect(endpoint.peers[0].address).toBe('2001:db8::1')
    expect(endpoint.peers[0].port).toBe(51820)
    expect(endpoint.peers[1].address).toBe('vpn.example.net')
    expect(endpoint.peers[1].port).toBe(51820)
  })

  it.each([
    ['', 'empty'],
    ['[Peer]\nPublicKey = p\nAllowedIPs = 0.0.0.0/0', 'missingInterface'],
    ['[Interface]\nAddress = 10.0.0.2/32', 'missingPrivateKey'],
    ['[Interface]\nPrivateKey = key', 'missingAddress'],
    ['[Interface]\nPrivateKey = key\nAddress = 10.0.0.2/32', 'missingPeers'],
    ['[Interface]\nPrivateKey = key\nAddress = 10.0.0.2/32\n[Peer]\nAllowedIPs = 0.0.0.0/0', 'missingPeerKey'],
    ['[Interface]\nPrivateKey = key\nAddress = 10.0.0.2/32\n[Peer]\nPublicKey = p', 'missingAllowedIps'],
    ['[Interface]\nPrivateKey = key\nAddress = 10.0.0.2/32\nListenPort = 70000\n[Peer]\nPublicKey = p\nAllowedIPs = 0.0.0.0/0', 'invalidPort'],
  ] as const)('rejects %s with %s', (conf, code) => {
    expect(() => parseWireguardConf(conf)).toThrowError(code)
  })
})
